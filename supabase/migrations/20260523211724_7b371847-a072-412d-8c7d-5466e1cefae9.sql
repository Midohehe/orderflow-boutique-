
CREATE TABLE public.shipping_price_lists (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  region text NOT NULL,
  cities text NOT NULL,
  price numeric NOT NULL DEFAULT 0,
  duration text,
  sort_order int NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.shipping_price_lists ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Anyone can read shipping prices"
  ON public.shipping_price_lists FOR SELECT
  USING (true);

CREATE POLICY "Admins can insert shipping prices"
  ON public.shipping_price_lists FOR INSERT
  WITH CHECK (has_role(auth.uid(), 'admin'::app_role));

CREATE POLICY "Admins can update shipping prices"
  ON public.shipping_price_lists FOR UPDATE
  USING (has_role(auth.uid(), 'admin'::app_role));

CREATE POLICY "Admins can delete shipping prices"
  ON public.shipping_price_lists FOR DELETE
  USING (has_role(auth.uid(), 'admin'::app_role));

CREATE TRIGGER tg_shipping_price_lists_updated
  BEFORE UPDATE ON public.shipping_price_lists
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

